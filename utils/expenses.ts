/**
 * ID로 지출 기록 조회
 */
export async function getExpenseById(id: string): Promise<ExpenseRecord | null> {
  if (!isSupabaseConfigured) {
    console.warn('[expenses] Supabase not configured, skipping get');
    return null;
  }

  try {
    let query = supabase
      .from('expenses')
      .select('*')
      .eq('id', id);

    // 로그인 사용자 또는 게스트 구분
    try {
      const { data: { user }, error: authError } = await supabase.auth.getUser();
      if (!authError && user) {
        // 로그인 사용자: auth_uid로 필터링
        query = query.eq('auth_uid', user.id);
      } else {
        // 게스트 사용자: device_id로 필터링
        const deviceId = await getOrCreateDeviceId();
        query = query.eq('device_id', deviceId).is('auth_uid', null);
      }
    } catch (authErr) {
      // 인증 에러 발생 시 게스트로 처리
      const deviceId = await getOrCreateDeviceId();
      query = query.eq('device_id', deviceId).is('auth_uid', null);
    }

    const { data, error } = await query.single();

    if (error) {
      if (error.code === 'PGRST116') {
        // 레코드를 찾지 못함
        return null;
      }
      console.error('[expenses] Get error:', error);
      throw error;
    }

    if (!data) {
      return null;
    }

    return convertFromSupabaseFormat(data);
  } catch (error) {
    console.error('[expenses] Failed to get expense:', error);
    throw error;
  }
}

/**
 * 날짜 범위로 지출 기록 조회
 */
export async function getExpensesByDateRange(
  startDate: string, // YYYY.MM.DD 형식
  endDate: string // YYYY.MM.DD 형식
): Promise<ExpenseRecord[]> {
  if (!isSupabaseConfigured) {
    console.warn('[expenses] Supabase not configured, skipping get by date range');
    return [];
  }

  try {
    // 현재 사용자 확인 (로그인 또는 게스트)
    let query = supabase
      .from('expenses')
      .select('*')
      .gte('date', startDate)
      .lte('date', endDate);

    // 로그인 사용자 또는 게스트 구분
    try {
      const { data: { user }, error: authError } = await supabase.auth.getUser();
      if (!authError && user) {
        // 로그인 사용자: auth_uid로 필터링
        query = query.eq('auth_uid', user.id);
      } else {
        // 게스트 사용자: device_id로 필터링
        const deviceId = await getOrCreateDeviceId();
        query = query.eq('device_id', deviceId).is('auth_uid', null);
      }
    } catch (authErr) {
      // 인증 에러 발생 시 게스트로 처리
      const deviceId = await getOrCreateDeviceId();
      query = query.eq('device_id', deviceId).is('auth_uid', null);
    }

    const { data, error } = await query.order('timestamp', { ascending: false });

    if (error) {
      console.error('[expenses] Get by date range error:', error);
      throw error;
    }

    if (!data || data.length === 0) {
      return [];
    }

    return data.map(convertFromSupabaseFormat);
  } catch (error) {
    console.error('[expenses] Failed to get expenses by date range:', error);
    throw error;
  }
}

